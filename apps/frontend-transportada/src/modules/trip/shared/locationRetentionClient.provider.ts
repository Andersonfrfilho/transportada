import { getIdentityEnvironment } from '@/modules/identity/shared/identityEnvironment.config'
import { getKeycloakAuthProvider } from '@/modules/identity/shared/KeycloakAuthProvider.provider'

import {
  createLocationRetentionClient,
  type LocationRetentionClient,
} from './locationRetentionClient.service'

export function getLocationRetentionClient(): LocationRetentionClient {
  return createLocationRetentionClient({
    apiBaseUrl: getIdentityEnvironment().apiBaseUrl,
    fetch: (request) => fetch(request),
    getAccessToken: () => getKeycloakAuthProvider().getAccessToken(),
  })
}
